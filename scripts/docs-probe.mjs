#!/usr/bin/env node
/**
 * Runtime half of the documentation gate.
 *
 * `make check-docs` proves that a document points at things that exist. It
 * cannot prove that the *names* a document advertises still mean anything,
 * because those names live inside a running engine. This script closes that
 * gap for the debug DSL: it reads every runtime field out of
 * `docs/debug-dsl.md`, feeds each one to a real binary, and fails on the first
 * name the runtime no longer resolves.
 *
 * It also compares the `DEBUG_CONTROL ready` line the binary prints against the
 * example in the documentation. That line is generated by
 * `DebugControlCommandGroups()`, so a mismatch means a command was added to or
 * removed from the parser without the document following.
 *
 * Usage:
 *   node scripts/docs-probe.mjs [--root DIR] [--binary PATH] [--batch N]
 *                               [--json] [--verbose] [--keep]
 *
 * The probe refuses to fabricate a pass: without a Wayland session it reports
 * `skipped` and exits non-zero only when `--require-display` is passed, so CI on
 * a headless runner can distinguish "not applicable" from "verified".
 */

import { execFileSync, spawn } from 'node:child_process'
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'

const argv = process.argv.slice(2)
/** @param {string} name */
function option(name, fallback = null) {
  const index = argv.indexOf(name)
  return index >= 0 && argv[index + 1] ? argv[index + 1] : fallback
}

const root = resolve(option('--root', process.cwd()))
const binary = resolve(root, option('--binary', 'build/normal/voxelcraft'))
const batchSize = Number.parseInt(option('--batch', '40'), 10)
const verbose = argv.includes('--verbose')
const asJson = argv.includes('--json')
const keep = argv.includes('--keep')
const requireDisplay = argv.includes('--require-display')
const docPath = join(root, 'docs/debug-dsl.md')
const timeoutSeconds = Number.parseInt(option('--timeout', '240'), 10)

/** Report a result and exit. @param {object} result @param {number} code */
function finish(result, code) {
  if (asJson) console.log(JSON.stringify(result, null, 2))
  else {
    for (const line of result.messages) console.log(line)
    for (const line of result.failures) console.error(`error ${line}`)
    console.log(
      `docs-probe: ${result.status}  fields=${result.fields ?? 0} ` +
        `resolved=${result.resolved ?? 0} unresolved=${result.failures.length}`
    )
  }
  process.exit(code)
}

if (!existsSync(binary)) {
  finish({ status: 'failed', failures: [`binary not found: ${binary} (run make first)`], messages: [] }, 1)
}
if (!existsSync(docPath)) {
  finish({ status: 'failed', failures: [`documentation not found: ${docPath}`], messages: [] }, 1)
}

const display = process.env.WAYLAND_DISPLAY
const runtimeDir = process.env.XDG_RUNTIME_DIR
const hasDisplay = Boolean(display && runtimeDir)
if (!hasDisplay) {
  const message =
    'skipped: no Wayland session (WAYLAND_DISPLAY/XDG_RUNTIME_DIR unset); ' +
    'runtime field resolution needs a real frame loop'
  if (requireDisplay) finish({ status: 'failed', failures: [message], messages: [] }, 1)
  finish({ status: 'skipped', messages: [message], failures: [] }, 0)
}

/**
 * Extract the runtime namespace fields a document advertises.
 *
 * The names live in the `| \`field.name\` |` cells of the namespace tables. A
 * cell can list several names separated by commas, and a name may carry no
 * dots (bare booleans). Table rows only count inside the namespace sections, so
 * unrelated tables in the same file do not produce names.
 * @param {string} source
 * @returns {{ names: string[], byName: Map<string, number> }}
 */
function documentedFields(source) {
  const names = []
  const byName = new Map()
  let inNamespaces = false
  for (const [index, line] of source.split('\n').entries()) {
    if (/^##\s/.test(line)) {
      inNamespaces = /runtime (namespace|namespaces|field)/i.test(line) || /运行时/.test(line)
    }
    if (!inNamespaces || !line.startsWith('|')) continue
    // The first cell can carry several names, either as `a.b`, `c.d` or inside
    // one pair of backticks separated by commas. Both forms are documented
    // names and both have to resolve.
    const firstCell = line.slice(1).split('|')[0]
    for (const span of firstCell.matchAll(/`([^`]+)`/g)) {
      for (const candidate of span[1].split(',')) {
        const name = candidate.trim()
        if (!/^[a-z][a-z0-9_]*(\.[a-z0-9_]+)*$/.test(name)) continue
        if (byName.has(name)) continue
        byName.set(name, index + 1)
        names.push(name)
      }
    }
  }
  return { names, byName }
}

const source = readFileSync(docPath, 'utf8')
const { names, byName } = documentedFields(source)
if (names.length === 0) {
  finish(
    { status: 'failed', failures: ['no runtime fields found; the namespace tables changed shape'], messages: [] },
    1
  )
}

/**
 * Turn a field name into a unique, legal DSL variable name.
 * @param {string} name
 */
function variableFor(name) {
  return `probe_${name.replace(/\./g, '_')}`
}

/**
 * Build a scene that boots, waits for play, then probes one batch of names.
 * `terrain flat` keeps boot deterministic; the wait is what the DSL calls
 * "playing", so the probe never reads a half-built world.
 * @param {string[]} batch
 */
function sceneFor(batch) {
  const lines = [
    '# generated by scripts/docs-probe.mjs',
    'terrain flat',
    'start',
    'wait until game.screen == "playing" timeout 7200'
  ]
  for (const name of batch) lines.push(`let ${variableFor(name)} = ${name}`)
  lines.push('exit 0')
  return `${lines.join('\n')}\n`
}

/**
 * Run one scene through the isolated scene runner and return its log.
 * @param {string} scenePath
 * @returns {{ log: string, code: number }}
 */
function runScene(scenePath) {
  try {
    const out = execFileSync(
      'bash',
      [
        join(root, 'scripts/run-scene.sh'),
        '--binary',
        binary,
        '--scene-file',
        scenePath,
        '--timeout',
        String(timeoutSeconds),
        '--resolution',
        '640x480'
      ],
      { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], timeout: (timeoutSeconds + 60) * 1000 }
    )
    const runDir = /run_dir=(\S+)/.exec(out)?.[1]
    const log = runDir && existsSync(join(runDir, 'game.log')) ? readFileSync(join(runDir, 'game.log'), 'utf8') : out
    return { log, code: 0 }
  } catch (error) {
    const stdout = error.stdout?.toString?.() ?? ''
    const stderr = error.stderr?.toString?.() ?? ''
    const combined = `${stdout}\n${stderr}`
    const runDir = /run_dir=(\S+)/.exec(combined)?.[1]
    const log = runDir && existsSync(join(runDir, 'game.log')) ? readFileSync(join(runDir, 'game.log'), 'utf8') : combined
    return { log, code: error.status ?? 1 }
  }
}

const workDir = mkdtempSync(join(tmpdir(), 'docs-probe-'))
const failures = []
const messages = []
let resolved = 0

try {
  for (let start = 0; start < names.length; start += batchSize) {
    const batch = names.slice(start, start + batchSize)
    const scenePath = join(workDir, `probe-${start}.dsl`)
    writeFileSync(scenePath, sceneFor(batch))
    const { log } = runScene(scenePath)

    // A failing `let` aborts the script, and the reply names the offending
    // expression rather than our probe variable. So a batch that errors has to
    // be re-run without the field that broke it; otherwise the fields after it
    // would be reported as verified without ever being evaluated.
    let pending = batch.slice()
    for (let attempt = 0; attempt < batch.length + 1 && pending.length > 0; attempt += 1) {
      const scene = attempt === 0 ? scenePath : join(workDir, `probe-${start}-${attempt}.dsl`)
      if (attempt > 0) writeFileSync(scene, sceneFor(pending))
      const result = attempt === 0 ? { log } : runScene(scene)
      const broken = [...result.log.matchAll(/undefined variable '([^']+)'/g)].map((match) => match[1])
      const attributed = pending.filter((name) => broken.includes(name))
      if (attributed.length === 0) {
        if (/DEBUG_SCRIPT error/.test(result.log)) {
          const error = /DEBUG_SCRIPT error.*/.exec(result.log)[0]
          failures.push(`docs/debug-dsl.md  probe batch starting at ${pending[0]} failed: ${error}`)
        } else {
          resolved += pending.length
        }
        break
      }
      for (const name of attributed) {
        failures.push(
          `docs/debug-dsl.md:${byName.get(name)}  ${name} does not resolve at runtime  (documented, but the parser or the field provider no longer exposes it)`
        )
        pending = pending.filter((other) => other !== name)
      }
    }
    if (verbose) messages.push(`probed ${Math.min(start + batchSize, names.length)}/${names.length}`)
  }

  // The ready line is generated from the parser; the document quotes it.
  const readyScene = join(workDir, 'ready.dsl')
  writeFileSync(readyScene, 'terrain flat\nstart\nwait until game.screen == "playing" timeout 7200\nexit 0\n')
  const { log: readyLog } = runScene(readyScene)
  const printed = /DEBUG_CONTROL ready mode=dsl.*/.exec(readyLog)?.[0]?.trim()
  const documented = /DEBUG_CONTROL ready mode=dsl[^`\n]*/.exec(source)?.[0]?.trim()
  if (!printed) {
    failures.push('docs-probe: the binary printed no DEBUG_CONTROL ready line')
  } else if (documented && printed !== documented) {
    failures.push(
      `docs/debug-dsl.md  ready line drifted\n  documented: ${documented}\n  actual:     ${printed}`
    )
  } else if (!documented) {
    failures.push('docs/debug-dsl.md  no ready line example found; the probe cannot compare it')
  }

  // Declared command smoke tests: each must be accepted and reply.
  const registry = JSON.parse(readFileSync(join(root, 'docs/doc-claims.json'), 'utf8'))
  const commands = registry.documents?.['docs/debug-dsl.md']?.probe?.commands ?? []
  if (commands.length > 0) {
    const smokeScene = join(workDir, 'commands.dsl')
    const lines = ['terrain flat', 'start', 'wait until game.screen == "playing" timeout 7200']
    for (const entry of commands) lines.push(entry.command)
    lines.push('exit 0')
    writeFileSync(smokeScene, `${lines.join('\n')}\n`)
    const { log } = runScene(smokeScene)
    for (const entry of commands) {
      if (!log.includes(entry.expect)) {
        failures.push(`docs/debug-dsl.md  command smoke failed: "${entry.command}" did not reply with "${entry.expect}"`)
      }
    }
  }
} finally {
  if (!keep) rmSync(workDir, { recursive: true, force: true })
  else messages.push(`probe scenes kept in ${workDir}`)
}

const status = failures.length === 0 ? 'passed' : 'failed'
finish({ status, fields: names.length, resolved, failures, messages }, failures.length === 0 ? 0 : 1)
